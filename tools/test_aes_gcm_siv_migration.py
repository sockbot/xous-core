"""
Compatibility tests for the AES-GCM-SIV migration from the custom rfc8452.py
implementation (using pyaesni) to the cryptography library's AESGCMSIV.

These tests verify that the AES_GCM_SIV wrapper class in rfc8452.py produces
correct results by checking against:
  1. RFC 8452 Appendix C known-answer test vectors (256-bit key)
  2. Golden ciphertexts generated by the original implementation
  3. Round-trip encrypt/decrypt correctness
  4. Error handling (ValueError on auth failure)
  5. Edge cases (empty plaintext, empty AAD, various data sizes)

Note: The PDDB only uses 256-bit keys. The old pyaesni-based implementation
only supported 256-bit keys (cbc256_encrypt), so 128-bit key tests are not
included.

Run with: python -m pytest test_aes_gcm_siv_migration.py -v
    or:   python test_aes_gcm_siv_migration.py
"""

import sys
import os
import unittest

# Ensure the tools directory is on the path so we can import rfc8452
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from rfc8452 import AES_GCM_SIV


class TestRfc8452AppendixC256NoAad(unittest.TestCase):
    """RFC 8452 Appendix C.2: AEAD_AES_256_GCM_SIV test vectors (no AAD).

    These vectors pass against both the old pyaesni-based implementation and
    the new cryptography-based implementation.
    """

    def test_vector_256bit_empty_pt_empty_aad(self):
        """C.2 first vector: empty plaintext, empty AAD, 256-bit key."""
        key = bytes.fromhex(
            '01000000000000000000000000000000'
            '00000000000000000000000000000000'
        )
        nonce = bytes.fromhex('030000000000000000000000')
        expected = bytes.fromhex('07f5f4169bbf55a8400cd47ea6fd400f')

        cipher = AES_GCM_SIV(key, nonce)
        ct = cipher.encrypt(b'', b'')
        self.assertEqual(ct, expected)

        cipher2 = AES_GCM_SIV(key, nonce)
        pt = cipher2.decrypt(ct, b'')
        self.assertEqual(pt, b'')

    def test_vector_256bit_8byte_pt(self):
        """C.2 second vector: 8-byte plaintext, no AAD, 256-bit key."""
        key = bytes.fromhex(
            '01000000000000000000000000000000'
            '00000000000000000000000000000000'
        )
        nonce = bytes.fromhex('030000000000000000000000')
        plaintext = bytes.fromhex('0100000000000000')
        expected = bytes.fromhex(
            'c2ef328e5c71c83b843122130f7364b7'
            '61e0b97427e3df28'
        )

        cipher = AES_GCM_SIV(key, nonce)
        ct = cipher.encrypt(plaintext, b'')
        self.assertEqual(ct, expected)

        cipher2 = AES_GCM_SIV(key, nonce)
        pt = cipher2.decrypt(ct, b'')
        self.assertEqual(pt, plaintext)


